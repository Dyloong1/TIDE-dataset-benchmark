"""Per-trajectory HARD acceptance gate for the corpus production line.

A single ~50 T_E corpus trajectory cannot pass the time-averaged isotropy items
(A10) or the long-window stationarity (A7) -- those are pooled over the seed
ensemble (CLAUDE.md decision 5). What MUST hold per trajectory is that the field
is physically correct and resolved:
  - resolution class != FAIL  (k_max*eta >= 1.0; Class I/II both publishable)
  - A2 resolved-dissipation fraction within the run's class
  - A12 incompressibility <= 1e-6
  - D-group D1-D4 (equation-level correctness): pass
Reads the run's metrics.json + its appendix tables. Exit 0 = accept this
trajectory's frames into the corpus; exit 1 = reject (quarantine + log).

    python check_corpus_traj.py <run_name>
"""
import json
import sys
from pathlib import Path

# UTF-8 console: REJECT-reason prints may echo non-ASCII cells from legacy appendices, so
# appendix; on Windows cp1252 that would crash the gate and bury the verdict.
try:
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
except Exception:
    pass

HERE = Path(__file__).parent
RES = HERE / "results"
name = sys.argv[1] if len(sys.argv) > 1 else ""
REC = RES / name

fail = []
try:
    m = json.load(open(REC / "metrics.json", encoding="utf-8"))
except Exception as e:
    print(f"[gate] {name}: cannot read metrics.json ({e}) -> REJECT")
    sys.exit(1)

kme = m.get("k_max_eta", 0.0)
cls = "I" if kme >= 1.5 else ("II" if kme >= 1.0 else "FAIL")
if cls == "FAIL":
    fail.append(f"resolution FAIL (k_max*eta={kme:.3f} < 1.0)")

# A14 sentinel must not have aborted (laminarized/collapsed trajectory)
if m.get("a14_aborted", False):
    fail.append("A14 sentinel aborted (eps collapse)")

# Stationarity is NOT judged on this (publish-window) trajectory. (2026-07-08, F5)
# The dt=0.05 publish window is 7.5 T_L, SHORTER than the OU integral-scale breathing
# period (O(10-14 T_L)). A K_drift linear fit over <1 breath aliases the breathing
# oscillation into a spurious secular slope: tests/test_eval_acceptance.py shows a
# PERFECTLY stationary field reads 8% drift at 7.5 T_L but 1.2% at 20 T_L, and — the
# reason no threshold can rescue it — a real 3-10%/5TL drift and pure breathing produce
# OVERLAPPING short-window drift (both 1-25%), so no short-window K_drift cut can tell
# them apart. Therefore we do NOT gate stationarity here.
#   - Stationarity of the CONFIG is established by its long (20 T_L) production window,
#     which every config passed 13-16/16 under the old dt=0.2 corpus (the standard is
#     unchanged: A7 <=1%/T_E, K_drift <=5%, judged on a window longer than the breath).
#   - The extreme non-stationary failure modes (laminarization / eps collapse) are still
#     caught PER TRAJECTORY by the A14 sentinel above (objective physics: eps/eps_W < 0.2
#     for >2 T_E aborts the run), not by a drift threshold.
# So the publish trajectory keeps only the window-INDEPENDENT gates (resolution, A2, A12,
# D1-D4, A14) — the ones a 7.5 T_L window can judge reliably.
_drift = m.get("K_drift_last5TL_pct", 0.0)  # recorded for provenance, NOT gated

# A2 + D-group from the per-run appendix. A2 is a per-FIELD resolution criterion
# (not a time-averaged pooled item like A10), so it MUST be judged per trajectory:
# the merged eval's A2 guard marks an under-resolved tail (slope a>=0) as FAIL /
# unresolvable, and such a field must not enter the corpus. D1-D4 must all pass
# (and D4 MISSING is NOT a pass).
# Marker vocabulary: current evals write English verdicts (pass/FAIL/unresolvable);
# appendices generated by earlier releases carry the same verdicts in Chinese.
# Both are accepted below (legacy markers spelled as \u escapes).
appx = REC / "DNS_STANDARD_APPENDIX_A.md"
_FAIL_MARKS = ("FAIL", "\u5931\u8d25")                 # FAIL / legacy
_PASS_MARKS = ("pass", "PASS", "\u901a\u8fc7")          # pass / legacy
_UNRESOLVED_MARKS = ("unresolvable", "\u4e0d\u53ef\u89e3\u6790")
d_pass = set()   # which of D1..D4 are present AND marked passing
if appx.exists():
    txt = appx.read_text(encoding="utf-8")
    for line in txt.splitlines():
        # A2 resolved-dissipation: FAIL or unresolvable/degenerate -> reject (under-resolved)
        if line.startswith("| A2") and (any(mk in line for mk in _FAIL_MARKS + _UNRESOLVED_MARKS) or "NA" in line):
            fail.append(f"A2 fail (under-resolved): {line.split('|')[2].strip()[:40]}")
        # D-group D1-D4: any FAIL OR MISSING fails the gate
        if line.startswith("| D") and (any(mk in line for mk in _FAIL_MARKS) or "MISSING" in line):
            fail.append(f"D-group fail/missing: {line.split('|')[1].strip()}")
        # record which D rows are present and passing (for the presence check below)
        for dk in ("D1", "D2", "D3", "D4"):
            if (line.startswith(f"| {dk} ") and any(mk in line for mk in _PASS_MARKS)
                    and not any(mk in line for mk in _FAIL_MARKS)):
                d_pass.add(dk)
else:
    fail.append("no acceptance appendix (eval A/B + showcase/eval-D missing)")
# PRESENCE GUARD: if eval-D crashed (e.g. showcase produced no dynamics_residuals.json),
# the D rows are simply absent and the loop above finds nothing to fail on -> a
# trajectory whose D-group was NEVER evaluated would slip through. Require all four.
missing_d = [dk for dk in ("D1", "D2", "D3", "D4") if dk not in d_pass]
if missing_d:
    fail.append(f"D-group not evaluated/passing: missing {','.join(missing_d)} "
                f"(showcase/eval-D may have failed -- the D-group must be assessed)")

print(f"[gate] {name}: k_max*eta={kme:.3f} (Class {cls}), drift={_drift:.2f}% (recorded, NOT gated — "
      f"stationarity by long window), a14_aborted={m.get('a14_aborted', False)}")
if fail:
    for f in fail:
        print(f"  REJECT: {f}")
    sys.exit(1)
print("  ACCEPT (per-trajectory hard criteria pass)")
sys.exit(0)
